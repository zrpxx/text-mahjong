export const ALL_DICTS = {
    grammar: DICT_GRAMMAR,
    actions: DICT_ACTIONS,
    nature: DICT_NATURE_WUXIA,
    meme: DICT_MODERN_MEME,
    descriptors: DICT_DESCRIPTORS
};

// 定义不同类别的权重（生成张数）
const CATEGORY_WEIGHTS: Record<keyof typeof ALL_DICTS, number> = {
    grammar: 4,     // 骨架词：4张（高频，相当于万能胶水）
    actions: 2,     // 动作：2张（标准对子）
    nature: 2,      // 意象：2张
    meme: 2,        // 梗：2张
    descriptors: 2  // 形容词：2张
};

export const generateDeck = (): Card[] => {
    let deck: Card[] = [];
    let idCounter = 0;

    // 遍历所有字典
    for (const [key, dict] of Object.entries(ALL_DICTS)) {
        // 获取当前类别的权重（如果没有定义则默认为 2）
        const categoryKey = key as keyof typeof ALL_DICTS;
        const copyCount = CATEGORY_WEIGHTS[categoryKey] || 2;

        for (const char of dict) {
            // 根据权重生成对应数量的牌
            for (let i = 0; i < copyCount; i++) {
                deck.push({
                    id: `${char}-${idCounter++}`, // Unique ID
                    char,
                    x: 0,
                    y: 0,
                    zIndex: 0
                });
            }
        }
    }

    // Fisher-Yates shuffle (洗牌算法)
    for (let i = deck.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        // 使用非空断言 ! 确保类型安全，因为索引在范围内
        const temp = deck[i]!;
        deck[i] = deck[j]!;
        deck[j] = temp;
    }

    return deck;
}